#!/usr/bin/env python3
"""Generate the comparison tables that support the paper's cross-era claims.

Only papers whose full text has been read (status read or verified) enter the
counts; the sample size per era is printed in every table so the reader can see
how thin each cell is.  Outputs:
  paper/tables/insights.tex   (included by 05-taxonomy / 06 / 12)
  docs/tables/insights.md
Tags are the catalog's coded values (see docs/methodology.md); they are not an
independent double coding.
"""
from collections import Counter, defaultdict
from _common import ROOT, papers

ERAS = [("era2", "Era 2 (1988--92)"), ("era3", "Era 3 (1993--2000)"), ("era4", "Era 4 (2000--10)"),
        ("era5", "Era 5 (2010--19)"), ("era6", "Era 6 (2020--26)")]
READ = [p for p in papers() if p["status"] in ("read", "verified")]
S = lambda p, k: set(p.get(k) or [])

def decision(p):
    crb = S(p, "compiler_runtime_boundary")
    if crb & {"profile-guided", "autotuned"}:
        return "profile or search"
    if "analytic-optimization" in crb:
        return "analytic optimisation"
    if "static-with-directives" in crb:
        return "programmer directives"
    if "fully-static" in crb:
        return "closed-form analysis"
    return "runtime only"

ELEM = {"communication-sets", "compiler-p2p", "message-vectorization", "import-export-schedule", "inspector-executor", "scatter-gather"}
COLL = {"reduction-allreduce", "all-to-all", "broadcast-multicast", "halo-exchange", "redistribution-resharding"}

def comm_family(p):
    c = S(p, "communication_generation")
    e, k = bool(c & ELEM), bool(c & COLL)
    return "both" if e and k else "element-level only" if e else "collective only" if k else "none recorded"

def rows_by_era(fn):
    out = []
    for era, label in ERAS:
        ps = [p for p in READ if p["era"] == era]
        out.append((label, len(ps), fn(ps)))
    return out

def table_decision():
    cats = ["programmer directives", "closed-form analysis", "analytic optimisation", "profile or search", "runtime only"]
    def f(ps):
        c = Counter(decision(p) for p in ps)
        return {k: c.get(k, 0) for k in cats}
    return cats, rows_by_era(f)

def table_objectives():
    objs = ["communication-volume", "message-count", "load-balance", "local-memory-fit", "overlap", "latency", "productivity", "performance-portability", "search-cost"]
    def f(ps):
        return {o: sum(1 for p in ps if o in S(p, "optimization_objectives")) for o in objs}
    return objs, rows_by_era(f)

def table_decomposition():
    vocab = ["block-cyclic", "affine-owner-map", "halo-overlap", "model-state-sharding", "sparse-tensor-partition", "mapping-array"]
    def f(ps):
        return {v: sum(1 for p in ps if v in S(p, "data_decomposition")) for v in vocab}
    return vocab, rows_by_era(f)

def table_comm():
    fams = ["element-level only", "collective only", "both"]
    def f(ps):
        c = Counter(comm_family(p) for p in ps)
        return {k: c.get(k, 0) for k in fams}
    return fams, rows_by_era(f)

def table_owner():
    kinds = ["owner-computes", "partition-propagation"]
    def f(ps):
        return {k: sum(1 for p in ps if k in S(p, "computation_mapping")) for k in kinds}
    return kinds, rows_by_era(f)

def tex_table(caption, label, heads, data):
    lines = ["% AUTO-GENERATED by scripts/generate_insights.py -- do not edit by hand.",
             "\\begin{table}[t]", "\\centering", "\\scriptsize", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             "\\begin{tabular}{l" + "r" * len(heads) + "}", "\\toprule",
             "Era (papers read) & " + " & ".join(h.replace("_", "\\_").replace("-", "-") for h in heads) + " \\\\", "\\midrule"]
    for name, n, vals in data:
        cells = " & ".join(str(vals[h]) for h in heads)
        lines.append(f"{name} (n={n}) & {cells} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)

def md_table(title, heads, data):
    out = [f"## {title}", "", "| era (papers read) | " + " | ".join(heads) + " |", "|---|" + "---|" * len(heads)]
    for name, n, vals in data:
        out.append(f"| {name} (n={n}) | " + " | ".join(str(vals[h]) for h in heads) + " |")
    return "\n".join(out) + "\n"

def main():
    specs = [
        ("insights-decision", "Decision procedure for the decomposition, by era. Counts are papers whose full text was read.", "tab:decision", table_decision, "Decision procedure"),
        ("insights-objectives", "Optimisation objectives recorded for read papers, by era. A paper may carry several objectives.", "tab:objectives", table_objectives, "Optimisation objectives"),
        ("insights-decomposition", "Data-decomposition vocabulary in read papers, by era.", "tab:decomposition-vocab", table_decomposition, "Data-decomposition vocabulary"),
        ("insights-communication", "Communication family in read papers, by era: element-level (sets, point-to-point, inspector schedules) versus collective.", "tab:comm-family", table_comm, "Communication family"),
        ("insights-owner", "Owner-computes versus partition propagation in read papers, by era.", "tab:owner", table_owner, "Owner rule"),
    ]
    md = ["# Cross-era comparison tables", "", "<!-- AUTO-GENERATED by scripts/generate_insights.py -- do not edit -->", "",
          f"Sample: {len(READ)} catalog papers with full text read. Era 0 and Era 1 have none; their claims are not tested here.", ""]
    for stem, cap, label, fn, title in specs:
        heads, data = fn()
        with open(ROOT / "paper" / "tables" / f"{stem}.tex", "w", encoding="utf-8") as f:
            f.write(tex_table(cap, label, heads, data))
        md.append(md_table(title, heads, data))
    (ROOT / "docs" / "tables" / "insights.md").write_text("\n".join(md), encoding="utf-8")
    print("insight tables written; sample", len(READ))

if __name__ == "__main__":
    main()
