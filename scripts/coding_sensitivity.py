#!/usr/bin/env python3
"""Sensitivity of the cross-era counts to the choice of coding.

Each generalization is recounted under four codings of the 54 read papers:
  first        the catalog tags (first coding)
  second       the independent second coding
  intersection values both codings assign (conservative)
  union        values either coding assigns (generous)
A generalization is reported as robust only when its direction is the same under
every coding. Output: docs/coding/sensitivity.md
"""
import glob, json, os
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
ERA = {e["id"]: f"Era {e['id'][3:]}" for e in yaml.safe_load(open("catalog/eras.yaml", encoding="utf-8"))["eras"]}
AXES = ["data_decomposition", "computation_mapping", "communication_generation",
        "compiler_runtime_boundary", "optimization_objectives"]

papers = yaml.safe_load(open("catalog/papers.yaml", encoding="utf-8"))["papers"]
read = {p["id"]: p for p in papers if p["status"] in ("read", "verified")}
second = {}
for f in sorted(glob.glob("coding/second_coder_*.json")):
    second.update(json.load(open(f, encoding="utf-8")))

def codings():
    out = {}
    for name in ("first", "second", "intersection", "union"):
        c = {}
        for pid, p in read.items():
            row = {}
            for ax in AXES:
                a = set(p.get(ax) or [])
                b = set(second[pid].get(ax) or [])
                row[ax] = {"first": a, "second": b, "intersection": a & b, "union": a | b}[name]
            c[pid] = row
        out[name] = c
    return out

CODINGS = codings()
def tags(name, pid, ax):
    return CODINGS[name][pid][ax]

def era(pid):
    return read[pid]["era"]

def count_by_era(name, pred):
    res = {e: 0 for e in ERA}
    for pid in read:
        if pred(name, pid):
            res[era(pid)] += 1
    return res

def n_by_era():
    return {e: sum(1 for p in read if era(p) == e) for e in ERA}

IRREG = {"mapping-array", "graph-partition", "application-defined", "sparse-tensor-partition"}
RUNTIME = {"runtime-inspector", "adaptive", "jit"}
def g1_violations(name):
    bad = []
    for pid in read:
        dd = tags(name, pid, "data_decomposition")
        crb = tags(name, pid, "compiler_runtime_boundary")
        comm = tags(name, pid, "communication_generation")
        if dd & IRREG and not (crb & RUNTIME or "inspector-executor" in comm):
            bad.append(pid)
    return bad

def decision(name, pid):
    crb = tags(name, pid, "compiler_runtime_boundary")
    if crb & {"profile-guided", "autotuned"}:
        return "search"
    if "analytic-optimization" in crb:
        return "analytic"
    if "static-with-directives" in crb:
        return "directive"
    if "fully-static" in crb:
        return "closed-form"
    return "runtime-only"

def elem_family(name, pid):
    c = tags(name, pid, "communication_generation")
    e = bool(c & {"communication-sets", "compiler-p2p", "message-vectorization", "import-export-schedule", "inspector-executor", "scatter-gather"})
    k = bool(c & {"reduction-allreduce", "all-to-all", "broadcast-multicast", "halo-exchange", "redistribution-resharding"})
    return "both" if e and k else "element" if e else "collective" if k else "none"

lines = ["# Sensitivity of the cross-era claims to the coding", "",
         "<!-- AUTO-GENERATED by scripts/coding_sensitivity.py -->", "",
         "Counts per era over the read papers, recomputed under four codings. Era sample sizes: "
         + ", ".join(f"{ERA[e]} n={n}" for e, n in n_by_era().items()) + ".", ""]

def table(title, rows):
    lines.append(f"### {title}")
    lines.append("")
    lines.append("| coding | " + " | ".join(ERA[e] for e in ERA) + " |")
    lines.append("|---|" + "---|" * len(ERA))
    for name, vals in rows:
        lines.append(f"| {name} | " + " | ".join(str(vals[e]) for e in ERA) + " |")
    lines.append("")

lines.append("## G1: irregular ownership and the run-time stage")
lines.append("")
lines.append("The claim: where ownership is set by an irregular or user-defined map and the system generates the")
lines.append("communication for it, a run-time stage (inspection or adaptation during execution) is recorded.")
lines.append("Population A is every read paper with irregular or user-defined ownership. Population B keeps the")
lines.append("papers whose communication is generated by the system (any communication value other than")
lines.append("programmer-explicit). Population B is the claim's own scope, and it was fixed after the Era 4 papers")
lines.append("were coded: Co-Array Fortran leaves communication to the programmer, so it is outside the claim.")
lines.append("The load-time variant counts load-time evaluation of a user map as a run-time stage.")
lines.append("")
RUN = {"runtime-inspector", "adaptive", "jit"}
def g1_population(name, scope):
    out = []
    for pid in read:
        dd = tags(name, pid, "data_decomposition")
        if not (dd & IRREG):
            continue
        comm = tags(name, pid, "communication_generation")
        if scope == "B" and not (comm - {"programmer-explicit"}):
            continue
        out.append(pid)
    return out
def g1_exceptions(name, scope, load_time=False):
    run = RUN | ({"load-time"} if load_time else set())
    return [pid for pid in g1_population(name, scope)
            if not (tags(name, pid, "compiler_runtime_boundary") & run)
            and "inspector-executor" not in tags(name, pid, "communication_generation")]
for scope, label in (("A", "population A (irregular or user-defined ownership)"), ("B", "population B (claim scope: system-generated communication)")):
    for name in ("first", "second", "intersection", "union"):
        pop = g1_population(name, scope)
        exc = g1_exceptions(name, scope)
        exc_lt = g1_exceptions(name, scope, load_time=True)
        lines.append(f"- {label}, {name}: {len(pop) - len(exc)} of {len(pop)} have a run-time stage; "
                     f"exceptions: {', '.join(exc) if exc else 'none'}; "
                     f"exceptions if load time counts: {', '.join(exc_lt) if exc_lt else 'none'}")
lines.append("")

lines.append("## G2: decision procedure by era (papers per procedure)")
lines.append("")
lines.append("The claim tested here is that search-based decomposition is absent before 2019. Falsifiers are read papers")
lines.append("before 2019 whose decision procedure is profile or search, under each coding:")
lines.append("")
for name in ("first", "second", "intersection", "union"):
    early = [pid for pid in read if read[pid]["year"] < 2019 and decision(name, pid) == "search"]
    late = [pid for pid in read if read[pid]["year"] >= 2019 and decision(name, pid) == "search"]
    lines.append(f"- {name}: before 2019: {', '.join(early) if early else 'none'}; from 2019: {len(late)} papers")
lines.append("")
for proc in ("analytic", "search", "directive", "closed-form", "runtime-only"):
    rows = []
    for name in ("first", "second", "intersection", "union"):
        rows.append((name, count_by_era(name, lambda n, p, pr=proc: decision(n, p) == pr)))
    table(f"procedure = {proc}", rows)

lines.append("## G3: objectives by era")
lines.append("")
for obj in ("message-count", "local-memory-fit", "productivity", "communication-volume", "search-cost"):
    rows = []
    for name in ("first", "second", "intersection", "union"):
        rows.append((name, count_by_era(name, lambda n, p, o=obj: o in tags(n, p, "optimization_objectives"))))
    table(f"objective = {obj}", rows)

lines.append("## G4: block-cyclic and mapping-array by era")
lines.append("")
for dec in ("block-cyclic", "mapping-array", "halo-overlap", "model-state-sharding", "sparse-tensor-partition"):
    rows = []
    for name in ("first", "second", "intersection", "union"):
        rows.append((name, count_by_era(name, lambda n, p, d=dec: d in tags(n, p, "data_decomposition"))))
    table(f"decomposition = {dec}", rows)

lines.append("## G5: owner-computes and partition propagation by era")
lines.append("")
for cm in ("owner-computes", "partition-propagation"):
    rows = []
    for name in ("first", "second", "intersection", "union"):
        rows.append((name, count_by_era(name, lambda n, p, c=cm: c in tags(n, p, "computation_mapping"))))
    table(f"computation mapping = {cm}", rows)

lines.append("## G6: communication family by era")
lines.append("")
for fam in ("element", "collective", "both"):
    rows = []
    for name in ("first", "second", "intersection", "union"):
        rows.append((name, count_by_era(name, lambda n, p, f=fam: elem_family(n, p) == f)))
    table(f"family = {fam}", rows)

os.makedirs("docs/coding", exist_ok=True)
open("docs/coding/sensitivity.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("written docs/coding/sensitivity.md")

# ---- compact LaTeX table for the paper: first/second coding per era ----
def cell(name, pred):
    r = count_by_era(name, pred)
    return r

MEASURES = [
    ("search-based decomposition", lambda n, p: decision(n, p) == "search"),
    ("analytic optimisation", lambda n, p: decision(n, p) == "analytic"),
    ("objective: message count", lambda n, p: "message-count" in tags(n, p, "optimization_objectives")),
    ("objective: productivity", lambda n, p: "productivity" in tags(n, p, "optimization_objectives")),
    ("block-cyclic", lambda n, p: "block-cyclic" in tags(n, p, "data_decomposition")),
    ("mapping array", lambda n, p: "mapping-array" in tags(n, p, "data_decomposition")),
    ("model-state sharding", lambda n, p: "model-state-sharding" in tags(n, p, "data_decomposition")),
    ("sparse-tensor partition", lambda n, p: "sparse-tensor-partition" in tags(n, p, "data_decomposition")),
    ("halo overlap (decomposition)", lambda n, p: "halo-overlap" in tags(n, p, "data_decomposition")),
    ("owner-computes", lambda n, p: "owner-computes" in tags(n, p, "computation_mapping")),
    ("partition propagation", lambda n, p: "partition-propagation" in tags(n, p, "computation_mapping")),
    ("element-level communication only", lambda n, p: elem_family(n, p) == "element"),
    ("halo exchange (communication)", lambda n, p: "halo-exchange" in tags(n, p, "communication_generation")),
]
tex = ["% AUTO-GENERATED by scripts/coding_sensitivity.py -- do not edit by hand.",
       "\\begin{table*}[t]", "\\centering", "\\scriptsize",
       "\\caption{Counts of read papers per era under the first coding and the independent second coding, written first/second. Era sample sizes (read papers) are " + ", ".join(f"{ERA[e]} {n}" for e, n in n_by_era().items()) + ". A measure whose two counts disagree in direction is not reported as a finding.}",
       "\\label{tab:sensitivity}",
       "\\begin{tabular}{l" + "c" * len(ERA) + "}", "\\toprule",
       "Measure & " + " & ".join(ERA[e] for e in ERA) + " \\\\", "\\midrule"]
for label, pred in MEASURES:
    a = count_by_era("first", pred)
    b = count_by_era("second", pred)
    cells = " & ".join(f"{a[e]}/{b[e]}" for e in ERA)
    tex.append(f"{label.replace('_', chr(92)+'_')} & {cells} \\\\")
tex += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
os.makedirs("paper/tables", exist_ok=True)
open("paper/tables/sensitivity.tex", "w", encoding="utf-8").write("\n".join(tex))
print("written paper/tables/sensitivity.tex")
