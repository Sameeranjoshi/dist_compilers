#!/usr/bin/env python3
"""Agreement between the first coding (catalog tags) and an independent second coding.

Inputs:
  catalog/papers.yaml              first coding: the tag fields of read papers
  coding/second_coder_A.json       second coder, papers 1-27 (see docs/HANDOFF.md)
  coding/second_coder_B.json       second coder, papers 28-54
Outputs:
  docs/coding/agreement.md         per-axis and per-value agreement, disagreement list
  coding/disagreements.json        every disagreement, for adjudication

Agreement is computed over the 54 read papers. For each axis: exact-set agreement
(papers whose two tag sets are identical) and, per value, Cohen's kappa on present/absent.
"""
import json, os
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
AXES = ["data_decomposition", "computation_mapping", "communication_generation",
        "compiler_runtime_boundary", "optimization_objectives"]

papers = yaml.safe_load(open("catalog/papers.yaml", encoding="utf-8"))["papers"]
read = {p["id"]: p for p in papers if p["status"] in ("read", "verified")}
second = {}
for f in ("coding/second_coder_A.json", "coding/second_coder_B.json"):
    second.update(json.load(open(f, encoding="utf-8")))
missing = sorted(set(read) - set(second))
if missing:
    raise SystemExit(f"no second coding for: {missing}")

def cohen_kappa(a, b):
    n = len(a)
    both = sum(1 for x, y in zip(a, b) if x and y)
    neither = sum(1 for x, y in zip(a, b) if not x and not y)
    po = (both + neither) / n
    pa, pb = sum(a) / n, sum(b) / n
    pe = pa * pb + (1 - pa) * (1 - pb)
    return 1.0 if pe == 1 else (po - pe) / (1 - pe)

lines = ["# Second coding: agreement with the first coding", "",
         "<!-- AUTO-GENERATED by scripts/second_coding_agreement.py -->", "",
         f"Papers compared: {len(read)} read papers. The second coder never saw the first coding.", ""]
disagreements = {}
for axis in AXES:
    lines.append(f"## {axis}")
    exact = 0
    values = set()
    for pid in read:
        a = set(read[pid].get(axis) or [])
        b = set(second[pid].get(axis) or [])
        values |= a | b
        if a == b:
            exact += 1
        else:
            disagreements.setdefault(pid, {})[axis] = {"first": sorted(a), "second": sorted(b)}
    lines.append(f"Exact-set agreement: {exact}/{len(read)} papers ({100*exact/len(read):.0f}%).")
    lines.append("")
    lines.append("| value | papers first | papers second | both | kappa |")
    lines.append("|---|---|---|---|---|")
    ids = sorted(read)
    for v in sorted(values):
        a = [v in (read[p].get(axis) or []) for p in ids]
        b = [v in (second[p].get(axis) or []) for p in ids]
        k = cohen_kappa(a, b)
        lines.append(f"| {v} | {sum(a)} | {sum(b)} | {sum(x and y for x, y in zip(a, b))} | {k:.2f} |")
    lines.append("")

lines.append("## Papers with at least one disagreement")
lines.append("")
for pid in sorted(disagreements):
    lines.append(f"- `{pid}`: " + "; ".join(
        f"{ax}: first={d['first']} second={d['second']}" for ax, d in disagreements[pid].items()))
os.makedirs("docs/coding", exist_ok=True)
open("docs/coding/agreement.md", "w", encoding="utf-8").write("\n".join(lines) + "\n")
json.dump(disagreements, open("coding/disagreements.json", "w", encoding="utf-8"), indent=1)
print(f"papers with a disagreement: {len(disagreements)} of {len(read)}")
