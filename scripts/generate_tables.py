#!/usr/bin/env python3
"""Generate LaTeX (paper/tables/*.tex) and Markdown (docs/tables/*.md) tables
from the catalog.  Tables:

  A era-summary          from catalog/eras.yaml
  B core-systems         from catalog/systems.yaml (table_b block)
  C decomposition-support from systems.decomposition_support
  D compiler-architecture from systems.compiler_architecture + papers
  E evaluation           from systems.table_b evaluation columns
  coverage               axis-value x era coverage matrix (Markdown only)

Also writes docs/tables/paper-list.md (every catalog paper with status).
"""
import re
from collections import defaultdict
from pathlib import Path

from _common import ROOT, eras, papers, systems, taxonomy

TEX = ROOT / "paper" / "tables"
MD = ROOT / "docs" / "tables"
TEX.mkdir(parents=True, exist_ok=True)
MD.mkdir(parents=True, exist_ok=True)

HEADER = "% AUTO-GENERATED by scripts/generate_tables.py from catalog/*.yaml -- do not edit by hand.\n"


def tex_escape(s):
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"), ("$", r"\$"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    return s


def md_escape(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def write_tex(name, caption, label, cols, rows, star=True, colspec=None, font=r"\scriptsize"):
    env = "table*" if star else "table"
    spec = colspec or ("p{%.2f\\textwidth}" % (0.95 / len(cols))) * len(cols)
    out = [HEADER, f"\\begin{{{env}}}[t]", r"\centering", font, f"\\caption{{{caption}}}", f"\\label{{{label}}}",
           f"\\begin{{tabular}}{{{spec}}}", r"\toprule",
           " & ".join(f"\\textbf{{{tex_escape(c)}}}" for c in cols) + r" \\", r"\midrule"]
    for r in rows:
        out.append(" & ".join(tex_escape(c) for c in r) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", f"\\end{{{env}}}", ""]
    (TEX / f"{name}.tex").write_text("\n".join(out), encoding="utf-8")


def write_md(name, title, cols, rows, note=None):
    out = [f"# {title}", "", "<!-- AUTO-GENERATED by scripts/generate_tables.py -- do not edit -->", ""]
    if note:
        out += [note, ""]
    out.append("| " + " | ".join(cols) + " |")
    out.append("|" + "---|" * len(cols))
    for r in rows:
        out.append("| " + " | ".join(md_escape(c) for c in r) + " |")
    out.append("")
    (MD / f"{name}.md").write_text("\n".join(out), encoding="utf-8")


def cite(ids):
    return ", ".join(f"\\cite{{{i}}}" for i in ids)


def main():
    E, S, P = eras(), systems(), papers()
    pmap = {p["id"]: p for p in P}
    tax = {a["key"]: {v["id"]: v["name"] for v in a["values"]} for a in taxonomy()["axes"]}

    # ---- Table A: eras --------------------------------------------------
    cols = ["Era", "Machine driver", "Programming abstraction", "Decomposition representation",
            "Generated communication", "Representative systems", "Limitation"]
    rows = []
    for i, e in enumerate(E):
        reps = [p for p in P if p["era"] == e["id"] and p["relevance_tier"] in ("core", "bridge")]
        reps = sorted(reps, key=lambda p: (p.get("start_here") or 99, p["year"]))[:4]
        rows.append([f"{i}: {e['name']} ({e['start']}--{e['end']})", e["machine_driver"], e["programming_abstraction"],
                     e["decomposition_representation"], e["generated_communication"],
                     "; ".join(f"{p['title'][:40]}... ({p['year']})" if len(p["title"]) > 40 else f"{p['title']} ({p['year']})" for p in reps),
                     e["limitation"]])
    write_md("table-a-eras", "Table A: Era summary", cols, rows)
    rows_tex = []
    for i, e in enumerate(E):
        reps = [p for p in P if p["era"] == e["id"] and p["relevance_tier"] in ("core", "bridge")]
        reps = sorted(reps, key=lambda p: (p.get("start_here") or 99, p["year"]))[:4]
        rows_tex.append([f"{i}: {e['name']} ({e['start']}--{e['end']})", e["machine_driver"], e["programming_abstraction"],
                         e["decomposition_representation"], e["generated_communication"],
                         "RAWCITE" + ",".join(p["id"] for p in reps), e["limitation"]])
    write_tex("table-a-eras", "Era summary. Dates are provisional (see Sec.~\\ref{sec:methodology}); representative systems are the catalog entries with the highest reading priority in each era.",
              "tab:eras", cols, rows_tex, colspec="p{0.11\\textwidth}p{0.12\\textwidth}p{0.14\\textwidth}p{0.14\\textwidth}p{0.14\\textwidth}p{0.10\\textwidth}p{0.15\\textwidth}")
    _fix_rawcite(TEX / "table-a-eras.tex")

    # ---- Table B: core systems ------------------------------------------
    cols = ["System", "Years", "Input", "Distribution", "Work mapping", "Communication", "Runtime", "Targets", "Artifact"]
    rows, rows_tex = [], []
    for s in sorted(S, key=lambda s: s["active_years"]):
        b = s.get("table_b") or {}
        base = [s["name"], s["active_years"], b.get("input", "?"), b.get("distribution", "?"), b.get("work_mapping", "?"),
                b.get("communication", "?"), b.get("runtime", s["runtime"]), b.get("targets", ", ".join(s["targets"])), b.get("artifact", s["open_source_status"])]
        rows.append(base)
        rows_tex.append(base[:1] + ["RAWCITE" + ",".join(s["papers"][:2])] + base[1:])
    write_md("table-b-systems", "Table B: Core systems", cols, rows,
             note="`?` marks a cell not yet filled from a primary source.")
    write_tex("table-b-systems", "Core systems in the catalog. A question mark marks a cell not yet verified from a primary source.",
              "tab:systems", ["System", "Refs"] + cols[1:], rows_tex,
              colspec="p{0.08\\textwidth}p{0.05\\textwidth}p{0.06\\textwidth}p{0.11\\textwidth}p{0.12\\textwidth}p{0.11\\textwidth}p{0.12\\textwidth}p{0.09\\textwidth}p{0.10\\textwidth}p{0.08\\textwidth}")
    _fix_rawcite(TEX / "table-b-systems.tex")

    # ---- Table C: decomposition support ---------------------------------
    keys = ["block", "cyclic", "block_cyclic", "replication", "halo", "dynamic", "irregular", "hierarchical"]
    cols = ["System"] + [k.replace("_", "-") for k in keys]
    sym = {"yes": "●", "partial": "◐", "no": "○", "unknown": "?"}
    tsym = {"yes": r"$\bullet$", "partial": r"$\circ\!\!\bullet$", "no": r"$\circ$", "unknown": "?"}
    rows, rows_tex = [], []
    for s in sorted(S, key=lambda s: s["active_years"]):
        d = s.get("decomposition_support") or {}
        rows.append([s["name"]] + [sym[d.get(k, "unknown")] for k in keys])
        rows_tex.append([s["name"]] + ["RAWTEX" + tsym[d.get(k, "unknown")] for k in keys])
    write_md("table-c-decomposition", "Table C: Decomposition support", cols, rows,
             note="● supported, ◐ partial, ○ not supported, ? not verified from a primary source.")
    write_tex("table-c-decomposition", "Decomposition support by system. $\\bullet$ supported, $\\circ\\!\\!\\bullet$ partial, $\\circ$ not supported, ? not yet verified.",
              "tab:decomposition", cols, rows_tex, star=False, colspec="l" + "c" * len(keys))
    _fix_rawtex(TEX / "table-c-decomposition.tex")

    # ---- Table D: compiler architecture ---------------------------------
    arch_cols = [("source-to-source", "src-to-src"), ("polyhedral", "polyhedral"), ("graph-compiler", "graph IR"),
                 ("multi-level-ir", "multi-level IR"), ("mlir-based", "MLIR"), ("compiler-runtime-codesign", "runtime co-design")]
    cols = ["System"] + [c[1] for c in arch_cols] + ["Generated target"]
    rows, rows_tex = [], []
    for s in sorted(S, key=lambda s: s["active_years"]):
        a = set(s.get("compiler_architecture", []))
        rows.append([s["name"]] + ["●" if k in a else "○" for k, _ in arch_cols] + [", ".join(tax["target_memory_model"].get(t, t) for t in s["targets"])])
        rows_tex.append([s["name"]] + ["RAWTEX" + (r"$\bullet$" if k in a else r"$\circ$") for k, _ in arch_cols] + [", ".join(tax["target_memory_model"].get(t, t) for t in s["targets"])])
    write_md("table-d-architecture", "Table D: Compiler architecture", cols, rows)
    write_tex("table-d-architecture", "Compiler architecture by system (from catalog tags).", "tab:architecture", cols, rows_tex,
              star=False, colspec="l" + "c" * len(arch_cols) + "p{0.3\\columnwidth}")
    _fix_rawtex(TEX / "table-d-architecture.tex")

    # ---- Table E: evaluation --------------------------------------------
    cols = ["System", "Benchmarks", "Baseline", "Scale", "Metrics", "Productivity eval.", "Artifact"]
    rows = []
    for s in sorted(S, key=lambda s: s["active_years"]):
        b = s.get("table_b") or {}
        rows.append([s["name"], b.get("benchmarks", "?"), b.get("baseline", "?"), b.get("scale", "?"), b.get("metrics", "?"),
                     b.get("productivity_eval", "?"), b.get("artifact", s["open_source_status"])])
    write_md("table-e-evaluation", "Table E: Evaluation methodology", cols, rows, note="`?` = not yet extracted from the primary source.")
    write_tex("table-e-evaluation", "Evaluation methodology by system. A question mark marks a cell not yet extracted from the primary source.",
              "tab:evaluation", cols, rows)

    # ---- coverage matrix ------------------------------------------------
    cov = defaultdict(lambda: defaultdict(int))
    field_of = {a["key"]: a["field"] for a in taxonomy()["axes"]}
    era_ids = [e["id"] for e in E]
    for p in P:
        for key, field in field_of.items():
            for v in (p.get(field) or []) if isinstance(p.get(field), list) else ([p.get(field)] if p.get(field) else []):
                cov[(key, v)][p["era"]] += 1
    rows = []
    for a in taxonomy()["axes"]:
        for v in a["values"]:
            counts = [cov[(a["key"], v["id"])][e] for e in era_ids]
            rows.append([f"{a['key']} / {v['id']}"] + [str(c) if c else "·" for c in counts] + [str(sum(counts))])
    write_md("coverage-matrix", "Taxonomy coverage matrix (axis value × era)", ["axis / value"] + era_ids + ["total"], rows,
             note="Counts of catalog papers carrying each tag per era. A dot is an empty cell and a candidate for the gap-snowball search (docs/methodology.md).")

    # ---- paper list -----------------------------------------------------
    cols = ["id", "year", "title", "type", "tier", "status", "verified", "access"]
    rows = [[p["id"], p["year"], p["title"], p["paper_type"], p["relevance_tier"], p["status"], "yes" if p["verified"] else "no", p["access_status"]]
            for p in sorted(P, key=lambda p: (p["year"], p["id"]))]
    write_md("paper-list", "All catalog papers", cols, rows)
    print(f"tables written: {len(list(TEX.glob('*.tex')))} tex, {len(list(MD.glob('*.md')))} md")


def _fix_rawcite(path):
    t = path.read_text(encoding="utf-8")
    t = re.sub(r"RAWCITE([a-z0-9,]*)", lambda m: ("\\cite{" + m.group(1) + "}") if m.group(1) else "--", t)
    path.write_text(t, encoding="utf-8")


def _fix_rawtex(path):
    t = path.read_text(encoding="utf-8")
    t = re.sub(r"RAWTEX(\\\$[^$]*\\\$)", lambda m: m.group(1).replace("\\$", "$").replace("\\textbackslash{}", "\\").replace("\\!", "\\!"), t)
    # tex_escape mangled the math; restore the three symbols explicitly
    t = t.replace(r"$\textbackslash{}bullet$", r"$\bullet$").replace(r"$\textbackslash{}circ$", r"$\circ$")
    t = t.replace(r"$\textbackslash{}circ\textbackslash{}!\textbackslash{}!\textbackslash{}bullet$", r"$\circ\!\!\bullet$")
    t = t.replace("RAWTEX", "")
    path.write_text(t, encoding="utf-8")


if __name__ == "__main__":
    main()
